import { expect, it } from "vitest";
import { savedProject } from "./savedProject";
import { integrateDemoUpdates } from "./demoUpdates";
import { validateProject } from "./model";
import { sceneView } from "./SceneViews";
import { addConnectedDialogue } from "./flow";
import { openNotification } from "./notifications";
import { start, advance } from "./model";
it("repairs wardrobe links and adds demo sounds and views once, preserving custom art, icons and café", () => {
  const source = savedProject(), p = savedProject();
  delete p.contentUpdates;
  const cafe = structuredClone(p.scenes.find(s => s.id === "cafe"));
  const s = p.scenes.find(s => s.id === "outfit")!;
  s.effects.brightness = 0.71;
  const photo = s.background;
  s.items!.options[0].choice = "missing";
  s.items!.options[0].description = "My custom garment note";
  s.items!.options.splice(1, 1);
  s.items!.enabled = false;
  p.scenes[0].phone!.appearance!.icons.feed = p.assets[0].id;
  p.scenes[0].subscenes = [];
  delete p.scenes[0].nodes.find(n => n.id === "monitor")!.view;
  const next = integrateDemoUpdates(p, source)!;
  const outfit = next.scenes.find(s => s.id === "outfit")!;
  expect(outfit.items!.options).toHaveLength(3);
  expect(outfit.items!.enabled).toBe(true);
  expect(outfit.items!.options[0].description).toBe("My custom garment note");
  expect(outfit.items!.options[0].choice).not.toBe("missing");
  expect(outfit.background).toBe(photo);
  expect(outfit.effects.brightness).toBe(.71);
  expect(next.scenes.find(s => s.id === "cafe")).toEqual(cafe);
  expect(next.scenes[0].phone!.appearance!.icons.feed).toBe(p.assets[0].id);
  expect(integrateDemoUpdates(next, source)).toBeNull();
  expect(() => validateProject(next)).not.toThrow();
});
it("sub-scene views restore the original image and never inherit misaligned region effects", () => {
  const p = savedProject(), s = p.scenes[0];
  const v = sceneView(s, "monitor");
  expect(v.background).toBe("first-match-monitor");
  expect(v.effects.rainZones).toEqual([]);
  expect(v.effects.lights).toEqual([]);
  expect(sceneView(s, "room")).toBe(s);
  const broken = structuredClone(p);
  broken.scenes[0].nodes[0].view = "unknown";
  expect(() => validateProject(broken)).toThrow("Missing dialogue sub-scene");
});
it("quick graph additions insert Continue and preserve existing routes when adding a reply", () => {
  const p = savedProject(), s = p.scenes[0], first = s.nodes[0];
  const previous = first.next;
  const id = addConnectedDialogue(p, s.id, first.id, "continue");
  expect(first.next).toBe(id);
  expect(s.nodes.find(n => n.id === id)!.next).toBe(previous);
  const reply = addConnectedDialogue(p, s.id, first.id, "reply");
  expect(first.choices.map(c => c.target)).toEqual([id, reply]);
  expect(first.next).toBeUndefined();
  expect(() => validateProject(p)).not.toThrow();
});
it("validates references for sound cues and app profile images", () => {
  const p = savedProject();
  p.scenes[0].nodes[0].sound = {asset: "missing", volume: .5};
  expect(() => validateProject(p)).toThrow("Missing sound cue asset");
  delete p.scenes[0].nodes[0].sound;
  p.scenes[0].phone!.appearance!.profiles.feed = "missing";
  expect(() => validateProject(p)).toThrow("Missing device appearance image");
});
it("opening an alert follows its authored next-decision route and applies its state actions", () => {
  const p = savedProject();
  const r = { ...start(p), node: "notification" };
  const next = openNotification(p, r);
  expect(next.node).toBe("cycle");
  expect(next.values.app_opened_first).toBe(true);
  const decision = advance(p, r);
  expect(openNotification(p, decision).node).toBe("cycle");
});
