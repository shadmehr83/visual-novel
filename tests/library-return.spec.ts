test('a device with no previous choices can be put down and picked back up without advancing',async({page})=>{
 const p=demo();p.id='return-without-options';p.scenes=p.scenes.slice(0,1);const s=p.scenes[0];
 s.effects.rain=false;s.nodes=[{id:'phone',speaker:'Narrator',text:'Browsing at my own pace',deviceScreen:'feed',next:'later',choices:[]},{id:'later',speaker:'Narrator',text:'Later on',deviceScreen:'off',choices:[]}];
 s.phone=makeDevice(s);delete s.phone.schedule;s.phone.mode='phone-system';s.phone.returnControl={enabled:true,start:'phone',end:'phone'};
 await page.goto('/');await page.locator('input[accept=".json"]').setInputFiles({name:'no-options.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(p))});
 await page.getByRole('button',{name:'Play story',exact:true}).click();
 await expect(page.locator('.scene-in .device-overlay')).toBeVisible();
 await page.getByRole('button',{name:'Put phone away',exact:true}).click();
 await expect(page.locator('.scene-in .device-overlay')).toBeHidden();
 await page.getByRole('button',{name:'Pick phone back up',exact:true}).click();
 await expect(page.locator('.scene-in .device-overlay')).toBeVisible();
 await expect(page.locator('.scene-in .device-story-progress p')).toHaveText('Browsing at my own pace');
});
