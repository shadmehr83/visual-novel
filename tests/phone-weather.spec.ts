import { test, expect } from '@playwright/test';
import { demo } from '../src/demo';
import { makeDevice } from '../src/deviceFrame';

test('weather is rainy all week, widget settings sync and contact strip stays in chat', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setViewportSize({ width: 1600, height: 1100 });
  const p = demo();
  p.scenes = p.scenes.slice(0, 1);
  const s = p.scenes[0];
  s.nodes = [{ id: 'start', speaker: 'Narrator', text: 'Testing the phone', choices: [] }];
  s.effects.rain = false;
  s.phone = makeDevice(s, 'Amber');
  s.phone.typingSeconds = 0;
  p.assets.push({ id: 'contact-test', name: 'Contact portrait', mime: 'image/png', width: 1, height: 1, data: 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', tags: '', notes: '', approved: false, reference: false });
  s.phone.avatar = 'contact-test';
  s.phone.entrance = { style: 'cut', seconds: 0.1 };
  await page.goto('/');
  await page.locator('input[accept=".json"]').setInputFiles({ name: 'weather.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(p)) });
  await page.getByRole('tab', { name: 'Advanced devices', exact: true }).click();
  const phone = page.locator('.device-live-preview .device-overlay');
  const settings = page.getByRole('region', { name: 'Advanced device settings', exact: true });
  await expect(phone.locator('.phone-weather-widget')).toBeVisible();
  await expect(phone.locator('.device-contact')).toHaveCount(0);
  await phone.locator('.phone-weather-widget').click();
  await expect(phone.getByRole('region', { name: 'Weekly weather' })).toBeVisible();
  await expect(phone.locator('.phone-weather-screen li')).toHaveCount(7);
  await expect(phone.locator('.phone-weather-screen li').filter({ hasText: 'Rain' })).toHaveCount(7);
  await expect(phone.locator('.device-contact')).toHaveCount(0);
  await phone.getByLabel('Back to phone home', { exact: true }).click();
  await phone.locator('.phone-app-grid').getByRole('button', { name: /Ember/ }).click();
  await expect(phone.locator('.device-contact')).toContainText('Amber');
  await expect(phone.locator('.device-contact img')).toBeVisible();
  await phone.locator('.phone-app-nav').getByRole('button', { name: 'Insta', exact: true }).click();
  await expect(phone.locator('.device-contact')).toHaveCount(0);
  await phone.getByLabel('Back to phone home', { exact: true }).click();
  await phone.locator('.phone-app-grid').getByRole('button', { name: /Settings/ }).click();
  await phone.getByLabel('Show weather widget', { exact: true }).uncheck();
  await page.getByRole('region', { name: 'Main workspace pane', exact: true }).getByRole('button', { name: 'Appearance', exact: true }).click();
  await expect(settings.getByLabel('Show weather widget', { exact: true })).not.toBeChecked();
  await phone.getByLabel('Back to phone home', { exact: true }).click();
  await expect(phone.locator('.phone-weather-widget')).toHaveCount(0);
  await phone.locator('.phone-app-grid').getByRole('button', { name: /Weather/ }).click();
  await expect(phone.locator('.phone-weather-screen li')).toHaveCount(7);
  await settings.getByLabel('Show weather widget', { exact: true }).check();
  await phone.getByLabel('Back to phone home', { exact: true }).click();
  await expect(phone.locator('.phone-weather-widget')).toBeVisible();
  await page.getByRole('button', { name: 'Back to dialogue editor', exact: true }).click();
  await page.locator('.effect-tabs').getByRole('button', { name: 'Phone', exact: true }).click();
  await expect(page.getByLabel('Show weather widget', { exact: true })).toBeChecked();
  await page.getByLabel('Show weather widget', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Open advanced devices', exact: true }).click();
  await expect(page.locator('.device-live-preview .phone-weather-widget')).toHaveCount(0);
  await expect(page.getByText('Saved on this device', { exact: true }).first()).toBeVisible();
  await page.reload();
  await page.getByRole('tab', { name: 'Advanced devices', exact: true }).click();
  await expect(page.locator('.device-live-preview .phone-weather-widget')).toHaveCount(0);
  await expect(page.locator('.device-live-preview .phone-app-grid').getByRole('button', { name: /Weather/ })).toBeVisible();
  expect(errors).toEqual([]);
});
